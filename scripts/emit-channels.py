#!/usr/bin/env python3
"""Print a ~/.config/guix/channels.scm for the commits CI is pinned to.

    ./scripts/emit-channels.py                 # to stdout
    ./scripts/emit-channels.py -w              # write ~/.config/guix/channels.scm
    ./scripts/emit-channels.py -o channels.scm # write elsewhere

WHY THIS EXISTS
===============
tests/channels-lock.scm pins the exact commits CI builds against, which is what
makes a red build reproducible -- but it is in `guix pull -C' form, not in the
channels.scm form a user's own ~/.config/guix/channels.scm needs, so the pins
have never been usable locally: a laptop follows guix master instead.  Someone
debugging "it builds in CI" needs the same commits here, and copying the
introductions by hand is exactly the sort of drift a lock file is supposed to
remove (the nonguix fingerprint is already duplicated in build.yml for that
reason).

The emitter is the inverse of retarget-channels-lock.py: that one rewrites the
two (commit ...) fields in place, this one reads the whole file and prints each
channel in the form `guix pull' or a channels.scm accepts.  It never writes to
channels-lock.scm, and it carries the introductions verbatim so the emitted file
is authenticated the same way CI is.

Note that sane-packages is NOT in the lock -- the lock covers the channels CI
pulls, not the channel under test, which build.yml gets from the checkout with
-L.  So the emitter adds it explicitly, pointing at the current branch by
default, because that is what someone reproducing a CI failure is running;
--no-self leaves it out.
"""
import argparse
import os
import re
import subprocess
import sys

CHANNEL_RE = re.compile(
    r'\(channel\s+'
    r"\(name\s+'?(?P<name>\S+?)'?\s*\)\s+"
    r'\(url\s+"(?P<url>[^"]+)"\s*\)\s+'
    r'\(commit\s+"(?P<commit>[0-9a-f]{40})"\s*\)',
    re.DOTALL,
)
INTRO_RE = re.compile(
    r'\(make-channel-introduction\s+"(?P<commit>[0-9a-f]{40})"\s+'
    r'\(openpgp-fingerprint\s+"(?P<fingerprint>[^"]+)"\s*\)\)'
)


def strip_comments(src: str) -> str:
    """Remove ; line comments, respecting strings.

    A string can hold a semicolon, and this file's comments hold parens and
    quotes, so the regexes above need the comments gone before they match.
    """
    out = []
    for line in src.splitlines():
        result = []
        in_string = False
        i = 0
        while i < len(line):
            c = line[i]
            if in_string:
                if c == "\\":
                    result.append(line[i:i + 2])
                    i += 2
                    continue
                if c == '"':
                    in_string = False
            elif c == '"':
                in_string = True
            elif c == ";":
                break
            result.append(c)
            i += 1
        out.append("".join(result))
    return "\n".join(out)


def channel_stubs(src: str) -> int:
    """Count (channel ...) forms, including ones the strict regex rejects.

    The emitter must never quietly drop a channel it does not understand: a
    user who follows guix master instead of the pinned commit gets an
    unreproducible build and no error.  So compare this count against what the
    regex actually parsed and refuse the difference.
    """
    # Strip strings first so a "(channel" inside a comment or a URL cannot
    # inflate the count.
    return src.count("(channel")


def format_fingerprint(fp: str) -> str:
    """OpenPGP fingerprints are shown space-separated in Guix's own docs."""
    words = fp.split()
    if len(words) > 1:
        return fp
    return " ".join(fp[i:i + 4] for i in range(0, len(fp), 4))


def emit(channels: list, include_self: bool, branch: str) -> str:
    parts = [";; Generated by scripts/emit-channels.py from tests/channels-lock.scm.\n"
             ";; Regenerate after bumping the lock: ./scripts/emit-channels.py -w\n"
             "(cons*"]
    if include_self:
        parts.append(
            "  (channel\n"
            "   (name 'sane-packages)\n"
            '   (url "https://github.com/khaalidrafi/packages")\n'
            f'   (branch "{branch}"))')
    for ch in channels:
        intro = ""
        if ch["intro"]:
            intro = (
                "\n   (introduction\n"
                f'    (make-channel-introduction\n'
                f'     "{ch["intro"][0]}"\n'
                "     (openpgp-fingerprint\n"
                f'      "{format_fingerprint(ch["intro"][1])}")))'
            )
        parts.append(
            "  (channel\n"
            f"   (name '{ch['name']})\n"
            f'   (url "{ch["url"]}")\n'
            f'   (commit "{ch["commit"]}"){intro})')
    parts.append("  %default-channels)")
    return "\n".join(parts) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-w", "--write", action="store_true",
                    help="write ~/.config/guix/channels.scm (or -o PATH)")
    ap.add_argument("-o", "--output",
                    help="write to this path instead of stdout")
    ap.add_argument("--no-self", action="store_true",
                    help="omit the sane-packages entry (lock content only)")
    ap.add_argument("--branch",
                    help="branch for the sane-packages entry (default: current)")
    args = ap.parse_args()

    lock = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "..", "tests", "channels-lock.scm")
    with open(lock, encoding="utf-8") as fh:
        src = strip_comments(fh.read())

    channels = []
    for m in CHANNEL_RE.finditer(src):
        # The introduction, when present, follows the commit inside the same
        # (channel ...) form; a windowed search keeps it from matching the next
        # channel's.
        rest = src[m.end():]
        nxt = rest.find("(channel")
        rest = rest[:nxt] if nxt >= 0 else rest
        intro = INTRO_RE.search(rest)
        channels.append({
            "name": m.group("name"),
            "url": m.group("url"),
            "commit": m.group("commit"),
            "intro": (intro.group("commit"), intro.group("fingerprint")) if intro else None,
        })
    if not channels:
        print("no channels parsed from " + lock, file=sys.stderr)
        return 1
    # A channel the strict regex skipped is a lock file this emitter does not
    # understand; emitting the rest would be worse than failing, because the
    # missing channel is the one that then tracks master.
    stubs = channel_stubs(src)
    if stubs != len(channels):
        print(f"parsed {len(channels)} channels but found {stubs} "
              "(channel ...) forms; refusing to emit a partial channel list",
              file=sys.stderr)
        return 1

    branch = args.branch
    if branch is None:
        try:
            branch = subprocess.run(
                ["git", "rev-parse", "--abbrev-ref", "HEAD"],
                capture_output=True, text=True, check=True).stdout.strip()
        except Exception:
            branch = "master"
    text = emit(channels, not args.no_self, branch)

    if args.output or args.write:
        path = args.output or os.path.join(
            os.environ.get("XDG_CONFIG_HOME",
                           os.path.expanduser("~/.config")),
            "guix", "channels.scm")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        # A file Guile will read: 644, not 755, and not the caller's umask
        # if that happens to be more open than this.
        os.chmod(path, 0o644)
        print("wrote " + path, file=sys.stderr)
        return 0

    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
